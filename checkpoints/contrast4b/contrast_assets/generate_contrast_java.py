#!/usr/bin/env python3
"""Generate the exact recovered LOW/HIGH Java tables; MEDIUM stays in its existing class."""
from __future__ import annotations
import base64
import gzip
import hashlib
import io
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent
OUTPUT = ROOT.parent / "PhotonCamera/app/src/main/java/com/particlesdevs/photoncamera/m10r/M10RContrastTables4B.java"
EXPECTED = {
    "low": "136b69127e73cc43c28c0aa7b511f1f3e9b29be139f4d491422f2eb574a49fb0",
    "high": "0a764cf29d35cd4a4eb7f816e5d128bccaef81b4d5eca991d9b80ab207bd0101",
}
COMMIT = "f93072b7d588e14329704a73ba64874cc16f0cf3"

def sha(data):
    return hashlib.sha256(data).hexdigest()

def pack(data):
    output = io.BytesIO()
    with gzip.GzipFile(filename="", mode="wb", compresslevel=9, fileobj=output, mtime=0) as stream:
        stream.write(data)
    result = output.getvalue()
    assert result[:10] == bytes.fromhex("1f8b08000000000002ff")
    assert gzip.decompress(result) == data
    return result

def source():
    holders = []
    records = {}
    for mode in ("low", "high"):
        data = (ROOT / ("tone_" + mode + "_q15.u32le")).read_bytes()
        assert len(data) == 40960 and sha(data) == EXPECTED[mode]
        compressed = pack(data)
        assert compressed == pack(data), "Compression must be deterministic"
        encoded = base64.b64encode(compressed).decode("ascii")
        chunks = [encoded[i:i + 100] for i in range(0, len(encoded), 100)]
        body = "\n".join('            "' + chunk + '"' + ("," if i + 1 < len(chunks) else "")
                         for i, chunk in enumerate(chunks))
        title = mode.capitalize()
        holders.append(
            "    private static final class " + title + "Holder {\n"
            "        private static final String[] B64 = {\n" + body + "\n"
            "        };\n"
            "        private static final int[] TABLE = M10RToneDg1A.decode32(B64, 10240);\n"
            "    }\n"
        )
        records[mode] = {
            "asset_sha256": sha(data), "asset_bytes": len(data),
            "gzip_bytes": len(compressed), "gzip_sha256": sha(compressed),
            "base64_characters": len(encoded), "string_chunks": len(chunks),
        }
    result = (
        "package com.particlesdevs.photoncamera.m10r;\n\n"
        "/**\n"
        " * Exact recovered M10-R still contrast LOW/HIGH Q15 gain tables.\n"
        " * MEDIUM (user-facing Standard) reuses M10RToneDg1A's unchanged existing table.\n"
        " * Generated by contrast_assets/generate_contrast_java.py; do not edit payloads.\n"
        " * Firmware B2Y SHA-256: ea935a8006ea3b0a765660bd1d89f6a52c9f60508ee5ba76650005d80372335b.\n"
        " * Extractor/evidence commit: " + COMMIT + ".\n"
        " * Tables are 10,240 little-endian uint32 values; unity is 32768 (Q15).\n"
        " * gzip has mtime=0, no filename and OS=255. Returned arrays are read-only by contract.\n"
        " * Payload identity does not establish complete ASIC normalization/rounding/routing parity.\n"
        " */\n"
        "final class M10RContrastTables4B {\n"
        '    static final String LOW_SHA256 = "' + EXPECTED["low"] + '";\n'
        '    static final String HIGH_SHA256 = "' + EXPECTED["high"] + '";\n\n'
        "    private M10RContrastTables4B() {}\n\n"
        "    static int[] low() { return LowHolder.TABLE; }\n"
        "    static int[] high() { return HighHolder.TABLE; }\n\n"
        + "\n".join(holders) + "}\n"
    )
    return result.encode("utf-8"), records

def main():
    data, records = source()
    checking = sys.argv[1:] == ["--check"]
    if sys.argv[1:] not in ([], ["--check"]):
        raise SystemExit("usage: generate_contrast_java.py [--check]")
    if checking:
        assert OUTPUT.read_bytes() == data, "Generated Java does not match exact deterministic source"
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_bytes(data)
        manifest = {
            "format": "m10r-contrast4b-java-generation-v1", "output": str(OUTPUT),
            "java_sha256": sha(data), "java_bytes": len(data), "tables": records,
            "compression": {"format": "gzip", "level": 9, "mtime": 0, "filename": "", "os": 255},
            "medium": "Existing M10RToneDg1A table; not duplicated",
        }
        (ROOT / "java_generation.json").write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n")
    print(json.dumps({"status": "PASS", "mode": "check" if checking else "generate",
                      "output": str(OUTPUT), "java_sha256": sha(data), "tables": records},
                     indent=2, sort_keys=True))

if __name__ == "__main__":
    main()
